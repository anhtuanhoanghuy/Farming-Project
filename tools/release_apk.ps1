# Release pipeline: bump version, build the release APK, name it with its SHA-256,
# log the release in document\release_pipeline.md and print the Supabase SQL.
#
# Usage (from anywhere):
#   .\tools\release_apk.ps1                         # CI mode (default): only bump version, 1.1.0+1 -> 1.1.1+2
#   .\tools\release_apk.ps1 -Bump minor            # only bump version (minor)
#   .\tools\release_apk.ps1 -Full -Notes "What changed"   # local: bump + build + SHA + log + SQL
#   .\tools\release_apk.ps1 -Full -DriveUrl "https://drive.google.com/file/d/ID/view?usp=sharing"
# Without -Full the script only bumps the version (GitHub Actions does build/release).
# In GitHub Actions, version_name / version_code are written to $GITHUB_OUTPUT.
param(
  [ValidateSet('patch', 'minor', 'major')][string]$Bump = 'patch',
  [string]$Notes = '',
  [string]$DriveUrl = 'PASTE_DRIVE_SHARE_LINK_HERE',
  [switch]$Full
)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$root = Split-Path $PSScriptRoot -Parent
$appDir = Join-Path $root 'flutter_app'
$pubspecPath = Join-Path $appDir 'pubspec.yaml'
$configPath = Join-Path $appDir 'lib\core\app_config.dart'
$outDir = Join-Path $root 'releases'
$pipelinePath = Join-Path $root 'document\release_pipeline.md'

$pubspec = [IO.File]::ReadAllText($pubspecPath)
$config = [IO.File]::ReadAllText($configPath)

$versionRe = [regex]'(?m)^version:\s*(\d+)\.(\d+)\.(\d+)\+(\d+)\s*$'
$m = $versionRe.Match($pubspec)
if (-not $m.Success) { throw 'Cannot find "version: x.y.z+n" in pubspec.yaml' }

$major = [int]$m.Groups[1].Value
$minor = [int]$m.Groups[2].Value
$patch = [int]$m.Groups[3].Value
$code = [int]$m.Groups[4].Value + 1
switch ($Bump) {
  'major' { $major++; $minor = 0; $patch = 0 }
  'minor' { $minor++; $patch = 0 }
  'patch' { $patch++ }
}
$name = "$major.$minor.$patch"
Write-Host "Version: $($m.Groups[1].Value).$($m.Groups[2].Value).$($m.Groups[3].Value)+$($m.Groups[4].Value) -> $name+$code"

$configRe = [regex]"static const appVersion = '[^']*';"
if (-not $configRe.IsMatch($config)) { throw 'Cannot find appVersion in app_config.dart' }

[IO.File]::WriteAllText($pubspecPath, $versionRe.Replace($pubspec, "version: $name+$code", 1), $utf8)
[IO.File]::WriteAllText($configPath, $configRe.Replace($config, "static const appVersion = '$name';", 1), $utf8)

if ($env:GITHUB_OUTPUT) {
  Add-Content -Path $env:GITHUB_OUTPUT -Value "version_name=$name", "version_code=$code" -Encoding utf8
}

if (-not $Full) {
  Write-Host "Version bumped only (use -Full for build, SHA, log and SQL)." -ForegroundColor Green
  return
}

try {
  Push-Location $appDir
  try {
    flutter build apk --release
    if ($LASTEXITCODE -ne 0) { throw "flutter build failed (exit $LASTEXITCODE)" }
  } finally {
    Pop-Location
  }
} catch {
  [IO.File]::WriteAllText($pubspecPath, $pubspec, $utf8)
  [IO.File]::WriteAllText($configPath, $config, $utf8)
  Write-Host 'Build failed: version files restored.' -ForegroundColor Red
  throw
}

$builtApk = Join-Path $appDir 'build\app\outputs\flutter-apk\app-release.apk'
if (-not (Test-Path $builtApk)) { throw "APK not found: $builtApk" }

$sha = (Get-FileHash $builtApk -Algorithm SHA256).Hash.ToLower()
$fileName = "sense_connect_v${name}_$($sha.Substring(0, 8)).apk"
New-Item -ItemType Directory -Force $outDir | Out-Null
$finalApk = Join-Path $outDir $fileName
Copy-Item $builtApk $finalApk -Force

$notesSql = $Notes.Replace("'", "''")
$sql = @"
insert into public.app_releases (version_code, version_name, apk_url, sha256, release_notes)
values ($code, '$name', '$DriveUrl', '$sha', '$notesSql');
"@

if (-not (Test-Path $pipelinePath)) {
  $header = "# Release pipeline`r`n`r`n" +
    "Generated by tools\release_apk.ps1. Each release: bump version, build APK, upload to Drive, run the SQL on Supabase.`r`n`r`n" +
    "| Date | Version | Code | APK file | SHA-256 |`r`n|---|---|---|---|---|`r`n"
  [IO.File]::WriteAllText($pipelinePath, $header, $utf8)
}
$date = Get-Date -Format 'yyyy-MM-dd HH:mm'
$entry = "| $date | $name | $code | $fileName | $sha |`r`n"
$text = [IO.File]::ReadAllText($pipelinePath)
$marker = "`r`n## Release SQL"
$idx = $text.IndexOf($marker)
if ($idx -ge 0) {
  $text = $text.Substring(0, $idx).TrimEnd() + "`r`n" + $entry + $text.Substring($idx)
} else {
  $text = $text.TrimEnd() + "`r`n" + $entry
}
$text = $text.TrimEnd() + "`r`n`r`n## Release SQL v$name (code $code)`r`n`r`n" + '```sql' + "`r`n$sql`r`n" + '```' + "`r`n"
[IO.File]::WriteAllText($pipelinePath, $text, $utf8)

Write-Host ''
Write-Host "APK:  $finalApk" -ForegroundColor Green
Write-Host "SHA:  $sha"
Write-Host ''
Write-Host 'Next: upload the APK to Google Drive (Anyone with the link), then run this on Supabase' -ForegroundColor Yellow
Write-Host '(replace the link if it still shows the placeholder):'
Write-Host ''
Write-Host $sql
